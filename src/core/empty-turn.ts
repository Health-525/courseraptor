/**
 * 空产出检测 —— 一轮跑完却什么都没说
 *
 * 场景：模型连上一次工具都没调、正文一个字都没有、思考也没有，流却正常收尾。
 * 此时网页端只发一个 `{t:"end"}`，用户看到的是「发出去、 spinner 转完、
 * 什么都没发生」——不知道是模型挂了、是自己网络断了、还是这次提问本身
 * 触发了什么过滤器。TUI 同理：光秃秃一行「完成 · 0.4s」，更让人困惑。
 *
 * 为什么单独一个模块而不是就地判断：网页端（web-stream-translate + chat-stream）
 * 与 TUI（inline.ts）都要用同一条判据，两边各写一遍必然漂移——一处判定
 * 「有思考也算产出」、另一处判「没有」，用户就会在两个渠道看到不一致的
 * 行为。所以判定与文案都在这里，纯函数、可单测。
 *
 * 边界（都是「不算空」）：
 * - 有工具调用：哪怕模型最终没说话，界面上也有工具卡，用户看得见发生了什么；
 *   真正的异常（如参数非法）由 tool-error 事件单独呈现。
 * - 有思考过程：深思模型可能先想再答，此刻还没到出正文的时候——但对用户
 *   而言思考卡已经渲染出来了，不是「什么都没发生」。
 * - 已有 failure：失败有它自己的错误文案与红色提示，不必再叠一条空产出。
 * - 用户主动中止（ESC / 关页面）：那是用户自己的选择，不是异常。
 */

/** 空产出时给用户的一句话。刻意写清「不是你的错」与「怎么试」——
 *  模型侧异常对用户是黑盒，指令必须可执行，否则等于没提示 */
export const EMPTY_TURN_HINT =
  "模型这一轮没有返回内容（既没有正文也没有工具调用）。多半是模型侧的临时异常，过十几秒重发一次通常就好；如果反复出现，换个模型或检查 API Key 是否有额度。";

export interface TurnOutput {
  /** 是否产出了正文（调用方只需判定「有没有」，不必把全文传进来） */
  hasText: boolean;
  /** 是否产出了思考过程 */
  hasThink: boolean;
  /** 是否发生过任何工具调用（含失败的工具调用） */
  hadToolCall: boolean;
  /** 失败信息（非 null 表示这一轮已有自己的错误口径） */
  failure: string | null;
  /** 用户是否主动中止 */
  aborted: boolean;
}

/**
 * 这一轮是否属于「空产出」。
 *
 * 判据是「什么都没发生」而非「没有正文」——只要界面上有任何可见痕迹
 * （思考卡、工具卡、错误行），就不该再补一条空产出提示，否则用户会
 * 同时看到「正在思考」和「模型没有返回内容」这种自相矛盾的两句话。
 */
export function isEmptyTurn(out: TurnOutput): boolean {
  if (out.aborted || out.failure) return false;
  if (out.hadToolCall) return false;
  return !out.hasText && !out.hasThink;
}
