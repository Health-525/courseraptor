/**
 * 河北农业大学贡献的系统提示词段：教务工具说明 + 学校背景知识
 *
 * core/prompt.ts 负责通用骨架，这里提供本校特有内容：已接入/未接入能力清单、
 * CAS 二次认证的行为规则、5.0 绩点口径。换一所学校 = 换一套这里的段文案。
 */

import type { SchoolPromptOptions, SchoolPromptSections } from "../../core/school";

export function hebauPromptSections(_options: SchoolPromptOptions): SchoolPromptSections {
  const tools = `教务查询：
- get_schedule：本学期课表（含节次时间段、当前周次；自动探测最新学期，也可指定如 2026-2027-1；放假/调休安排会自动叠加在对应周里）
- set_holidays：记录放假/调休安排（用户发来放假安排原文时逐日拆解落盘，课表自动叠加假期与调休覆盖）
- get_grades：全部学期成绩 + GPA（5.0 满绩制）与已获必修学分。问学分或挂科时引用工具结果，failedTerms 非空时先说明该学期数据不全
- get_exams：考试安排（含已报名未排考场的科目）
- export_calendar：课表/考试导出 .ics 日历文件（整学期逐周展开、跳过放假日、补出调休课、考试带提醒），手机日历导入即用
- export_schedule_image：把课表导出为图片（默认 PNG 红头档案风；整学期汇总或某一教学周均可）
- publish_calendar：把日历发布到用户配置的托管平台（Gitee/GitHub），返回手机日历可订阅的链接。首次发布前必须向用户说明内容会公开可见并确认
- submit_auth_code：提交学校统一认证的动态验证码（登录需要二次认证时用；code=验证码原文，challenge_id 用工具报错里给的那个）`;

  const background = `## 本校事实（河北农业大学）

- 认证走学校统一认证（CAS），教务数据来自正方 URP 学生端；统一认证在账密之后可能再要一个动态验证码（短信/微信/企业微信/邮箱/钉钉），工具会明确说「需要二次认证」并给出投递目标——这时向用户索要验证码，拿到后调 submit_auth_code，不要重复触发登录。
- 已接入能力：课表、成绩与 GPA、考试安排、日历导出。
- 未接入能力（学校教务系统没有提供对应接口）：自主选课/抢课、学籍个人信息、已选课程教学班、可重修课程、实验成绩、教务处通知列表与通知正文读取。用户问这些时如实说明本校尚未接入，建议去教务系统官网查看，不要拿其他学校的口径作答。
- 成绩绩点是 5.0 满绩制（百分制折算 = 分数/10 - 5），与 4.0 制不可混用；GPA 只算必修课，合格/免修/缓考类不参与。
- 节次时间与南工大不同（第 1 节 08:00-08:45），说上课时间以工具返回的 time 字段为准，不要按印象推。
- 校历参照：2026-2027 学年秋冬学期 9 月 1 日（周二）起上课、第 1 教学周自 2026-08-31（周一）起，春夏学期第 1 周自 2027-03-01（周一）起；周次计算以 get_schedule 返回的 week1Monday/weekSource 为准，weekSource=estimated 时要说明是估算值。
- 寒暑假与法定节假日安排学校没有开放接口也没有落盘记录时，回答「以学校通知/校历为准」，不要凭印象给具体日期。`;

  return { tools, background };
}
