/**
 * HEBAU 贡献的系统提示词段：教务工具说明 + 学校背景知识
 *
 * core/prompt.ts 负责通用骨架（身份、通用工具、行为准则、校历真值段），
 * 本文件提供河北农业大学特有的内容。与 njtech 的差异：无选课/抢课、
 * 无学籍（学校教务没开放对应接口），通知板块为本校的两个栏目，
 * 多出二次认证（CAS 动态码）说明。
 */

import type { SchoolPromptOptions, SchoolPromptSections } from "../../core/school";

export function hebauPromptSections(_options: SchoolPromptOptions): SchoolPromptSections {
  const tools = `教务查询：
- get_schedule：本学期课表（含节次时间段、当前周次；自动探测最新学期，也可指定如 2026-2027-1；放假/调休安排会自动叠加在对应周里）
- set_holidays：记录放假/调休安排（读放假通知后落盘，课表自动叠加假期与调休覆盖）
- get_exams：考试安排（已排考场与未排考场的都会返回，未排的 location/time 为空）
- get_grades：全部成绩 + GPA（5.0 满绩制，仅必修课计入）。问学分缺口或挂科时引用工具结果，不自行把未通过课程学分计入已获学分

二次认证：
- submit_auth_code：河北农大统一认证触发动态码二次认证后，用用户提供的验证码续完登录（get_schedule 等工具报「需要二次认证」时使用；challenge_id 以认证错误信息里给的为准）

通知情报：
- get_news：教务处官网（jiaowu.hebau.edu.cn）最新通知，两个板块：通知公告、教务动态。公网直连无需校园网。回答时优先讲 relevance=high 的（需本人行动），low 的一句带过。读到放假/调休安排的通知时，主动用 set_holidays 把日期落盘
- read_notice：读通知正文全文（时间安排/截止日期都在正文里；先 get_news 拿 URL 再读；也支持直接读用户发来的学校官网链接）
- fetch_attachment：读通知的文件附件（自动缓存免重下；表格回概览、长文分页续读/关键词定位）`;

  const background = `## 本校事实（河北农业大学）

- 认证走学校统一认证（CAS），教务数据来自正方 URP 学生端；统一认证在账密之后可能再要一个动态验证码（短信/微信/企业微信/邮箱/钉钉），工具会明确说「需要二次认证」并给出投递目标——这时向用户索要验证码，拿到后调 submit_auth_code，不要重复触发登录。
- 已接入能力：课表、成绩与 GPA、考试安排、日历导出（.ics）、教务处通知（官网公网可访问，无需校园网）。
- 未接入能力（学校教务系统没有提供对应接口，工具会直接返回「暂不支持」）：自主选课/抢课、学籍个人信息、已选课程教学班、可重修课程、实验成绩。用户问这些时如实说明本校尚未接入，建议去教务系统官网查看，不要拿其他学校的口径作答。
- 成绩绩点是 5.0 满绩制（百分制折算 = 分数/10 - 5），与南工大 4.0 制不可混用；GPA 只算必修课，合格/免修/缓考类不参与。
- 节次时间与南工大不同（第 1 节 08:00-08:45），说上课时间以工具返回的 time 字段为准，不要按印象推。
- 校历参照：2026-2027 学年秋冬学期第 1 周自 2026-09-01（周一）起，春夏学期第 1 周自 2027-03-01（周一）起；周次计算以 get_schedule 返回的 week1Monday/weekSource 为准，weekSource=estimated 时要说明是估算值。
- 寒暑假与法定节假日的具体安排以教务处通知为准：先 get_news 查「放假/调休」相关通知，读到就 read_notice 看正文并 set_holidays 落盘；查无通知再按「按国务院文件执行、另行通知」回答，不要凭印象给具体日期。`;

  return { tools, background };
}
